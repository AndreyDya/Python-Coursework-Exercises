# math_helpers_module.py - My custom module

# Create add function that adds two numbers
def add(a, b):
    """Add two numbers"""
    return a + b

# Create function that multiplies two numbers
def multiply(a, b):
    """Multiply two numbers"""
    return a * b

# Define a constant variable to hold the value of PI
PI = 3.14159

# Create a function that calculates the area of a circle
# from its radius
def calculate_area_of_circle(radius):
    """Calculate circle area"""
    return PI * radius * radius